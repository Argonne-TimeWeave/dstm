def require_file(path: Path, description: str) -> Path:
    resolved = path.expanduser().resolve()

    if not resolved.is_file():
        raise FileNotFoundError(f"{description} not found: {resolved}")

    return resolved


def require_data_directory(path: Path) -> Path:
    resolved = path.expanduser().resolve()

    if not resolved.is_dir():
        raise FileNotFoundError(f"data directory not found: {resolved}")

    node_path = resolved / "node.csv"
    link_path = resolved / "link.csv"

    if not node_path.is_file():
        raise FileNotFoundError(f"node.csv not found: {node_path}")
    if not link_path.is_file():
        raise FileNotFoundError(f"link.csv not found: {link_path}")

    return resolved


def expected_snapshot_path(mode: str, timestamp: int) -> Path:
    return Path.cwd() / f"staleness-{mode}-t{timestamp}-rank0.csv"


def run_simulation(args: argparse.Namespace) -> Path:
    executable = require_file(args.executable, "traffic executable")
    data_dir = require_data_directory(args.data)
    snapshot_path = expected_snapshot_path(args.mode, args.timestamp)

    # Prevent a failed simulation from accidentally causing an old dump to
    # be visualized as though it came from the current run.
    if snapshot_path.exists():
        snapshot_path.unlink()

    command = [
        args.launcher,
        *shlex.split(args.launcher_args),
        "-n",
        str(args.ranks),
        str(executable),
        "--data",
        str(data_dir),
        "--steps",
        str(args.steps),
        "--cars",
        str(args.cars),
        "--rate",
        str(args.rate),
        "--cap",
        str(args.cap),
        "--seed",
        str(args.seed),
        "--stale-delay",
        str(args.stale_delay),
        "--replica-mode",
        args.mode,
        "--snapshot-dump",
        str(args.timestamp),
        "--quiet",
    ]

    print("Running simulation:")
    print("  " + " ".join(command))
    print()

    # Run from scripts/vis so the C program writes its automatic snapshot
    # filename into this directory.
    result = subprocess.run(command, cwd=Path.cwd(), check=False)

    if result.returncode != 0:
        raise RuntimeError(
            f"graph_traffic failed with exit status {result.returncode}"
        )

    if not snapshot_path.is_file():
        raise FileNotFoundError(
            "simulation completed but did not create the expected snapshot: "
            f"{snapshot_path}"
        )

    return snapshot_path


def normalize_column_name(name: str) -> str:
    return name.strip().lower().replace("-", "_").replace(" ", "_")


def select_column(
    fieldnames: List[str],
    explicit_name: Optional[str],
    candidates: Tuple[str, ...],
    axis_name: str,
) -> str:
    normalized_to_actual = {
        normalize_column_name(name): name for name in fieldnames
    }

    if explicit_name is not None:
        normalized = normalize_column_name(explicit_name)
        actual = normalized_to_actual.get(normalized)

        if actual is None:
            raise ValueError(
                f"requested {axis_name} column {explicit_name!r} was not "
                f"found; available columns: {', '.join(fieldnames)}"
            )

        return actual

    for candidate in candidates:
        actual = normalized_to_actual.get(normalize_column_name(candidate))
        if actual is not None:
            return actual

    raise ValueError(
        f"could not determine the {axis_name} coordinate column in node.csv; "
        f"available columns: {', '.join(fieldnames)}. "
        f"Use --{axis_name}-column to specify it."
    )


def detect_csv_dialect(path: Path) -> csv.Dialect:
    with path.open("r", encoding="utf-8-sig", newline="") as input_file:
        sample = input_file.read(8192)

    try:
        return csv.Sniffer().sniff(sample, delimiters=",;\t")
    except csv.Error:
        return csv.excel


def load_node_coordinates(
    node_path: Path,
    x_column: Optional[str],
    y_column: Optional[str],
) -> Tuple[List[float], List[float], str, str]:
    dialect = detect_csv_dialect(node_path)

    with node_path.open("r", encoding="utf-8-sig", newline="") as input_file:
        reader = csv.DictReader(input_file, dialect=dialect)

        if reader.fieldnames is None:
            raise ValueError(f"{node_path} has no CSV header")

        fields = [name.strip() for name in reader.fieldnames]
        x_name = select_column(fields, x_column, X_COLUMN_CANDIDATES, "x")
        y_name = select_column(fields, y_column, Y_COLUMN_CANDIDATES, "y")

        x_values: List[float] = []
        y_values: List[float] = []

        for row_number, row in enumerate(reader, start=2):
            try:
                x_value = float(row[x_name])
                y_value = float(row[y_name])
            except (KeyError, TypeError, ValueError) as error:
                raise ValueError(
                    f"invalid coordinates in {node_path} at CSV row "
                    f"{row_number}: {error}"
                ) from error

            if not math.isfinite(x_value) or not math.isfinite(y_value):
                raise ValueError(
                    f"non-finite coordinates in {node_path} at CSV row "
                    f"{row_number}"
                )

            x_values.append(x_value)
            y_values.append(y_value)

    if not x_values:
        raise ValueError(f"no nodes were read from {node_path}")

    # The snapshot uses internal node indices. city_load() constructs those
    # indices from node.csv row order, so array index i corresponds to
    # snapshot node_id i.
    return x_values, y_values, x_name, y_name


def parse_int(value: Optional[str], field: str, row_number: int) -> int:
    if value is None or value.strip() == "":
        raise ValueError(f"missing {field} at snapshot row {row_number}")

    try:
        return int(value)
    except ValueError as error:
        raise ValueError(
            f"invalid integer {field}={value!r} at snapshot row {row_number}"
        ) from error


def parse_float(value: Optional[str], field: str, row_number: int) -> float:
    if value is None or value.strip() == "":
        raise ValueError(f"missing {field} at snapshot row {row_number}")

    try:
        return float(value)
    except ValueError as error:
        raise ValueError(
            f"invalid floating-point {field}={value!r} "
            f"at snapshot row {row_number}"
        ) from error

def load_snapshot(snapshot_path):
    nodes = {}
    edges = []

    required_fields = {
        "record_type",
        "node_id",
        "original_node_id",
        "x",
        "y",
        "owner",
        "edge_id",
        "src",
        "dst",
        "stamp",
        "age",
        "value",
        "known_edges",
        "total_edges",
        "partially_known",
    }

    with snapshot_path.open(
        "r", encoding="utf-8-sig", newline=""
    ) as input_file:
        reader = csv.DictReader(input_file)

        if reader.fieldnames is None:
            raise ValueError(
                "{} has no CSV header".format(snapshot_path)
            )

        missing_fields = required_fields - set(reader.fieldnames)
        if missing_fields:
            raise ValueError(
                "{} is missing fields: {}".format(
                    snapshot_path,
                    ", ".join(sorted(missing_fields)),
                )
            )

        for row_number, row in enumerate(reader, start=2):
            record_type = (
                row.get("record_type") or ""
            ).strip().lower()

            if record_type == "node":
                node_id = parse_int(
                    row.get("node_id"), "node_id", row_number
                )

                nodes[node_id] = {
                    "original_id": parse_int(
                        row.get("original_node_id"),
                        "original_node_id",
                        row_number,
                    ),
                    "x": parse_float(
                        row.get("x"), "x", row_number
                    ),
                    "y": parse_float(
                        row.get("y"), "y", row_number
                    ),
                    "owner": parse_int(
                        row.get("owner"), "owner", row_number
                    ),
                    "stamp": parse_int(
                        row.get("stamp"), "stamp", row_number
                    ),
                    "age": parse_float(
                        row.get("age"), "age", row_number
                    ),
                    "known_edges": parse_int(
                        row.get("known_edges"),
                        "known_edges",
                        row_number,
                    ),
                    "total_edges": parse_int(
                        row.get("total_edges"),
                        "total_edges",
                        row_number,
                    ),
                    "partially_known": parse_int(
                        row.get("partially_known"),
                        "partially_known",
                        row_number,
                    ),
                }

            elif record_type == "edge":
                edges.append({
                    "edge_id": parse_int(
                        row.get("edge_id"),
                        "edge_id",
                        row_number,
                    ),
                    "src": parse_int(
                        row.get("src"), "src", row_number
                    ),
                    "dst": parse_int(
                        row.get("dst"), "dst", row_number
                    ),
                    "stamp": parse_int(
                        row.get("stamp"), "stamp", row_number
                    ),
                    "age": parse_float(
                        row.get("age"), "age", row_number
                    ),
                    "value": parse_float(
                        row.get("value"), "value", row_number
                    ),
                })

            else:
                raise ValueError(
                    "unknown record_type={!r} at snapshot row {}".format(
                        record_type,
                        row_number,
                    )
                )

    if not nodes:
        raise ValueError(
            "{} contains no node records".format(snapshot_path)
        )

    if not edges:
        raise ValueError(
            "{} contains no edge records".format(snapshot_path)
        )

    for edge in edges:
        if edge["src"] not in nodes or edge["dst"] not in nodes:
            raise ValueError(
                "edge {} references missing dense node {} -> {}".format(
                    edge["edge_id"],
                    edge["src"],
                    edge["dst"],
                )
            )

    return nodes, edges

def coordinates_look_geographic(
    x_values: List[float],
    y_values: List[float],
    x_name: str,
    y_name: str,
) -> bool:
    normalized_x = normalize_column_name(x_name)
    normalized_y = normalize_column_name(y_name)

    explicitly_geographic = (
        normalized_x in {"longitude", "lon", "lng"}
        and normalized_y in {"latitude", "lat"}
    )

    within_lon_lat_ranges = (
        all(-180.0 <= value <= 180.0 for value in x_values)
        and all(-90.0 <= value <= 90.0 for value in y_values)
    )

    return explicitly_geographic or within_lon_lat_ranges


def project_coordinates(
    x_values: List[float],
    y_values: List[float],
    geographic: bool,
) -> Tuple[List[float], List[float]]:
    if not geographic:
        return x_values, y_values

    # Equirectangular projection around the graph's mean latitude. This
    # prevents longitude from appearing horizontally stretched.
    mean_latitude = sum(y_values) / len(y_values)
    longitude_scale = math.cos(math.radians(mean_latitude))

    projected_x = [value * longitude_scale for value in x_values]
    projected_y = List(y_values)

    return projected_x, projected_y


def percentile(values, percentage):
    if not values:
        return float("nan")

    ordered = sorted(values)

    if len(ordered) == 1:
        return ordered[0]

    position = (len(ordered) - 1) * percentage / 100.0
    lower = int(math.floor(position))
    upper = int(math.ceil(position))

    if lower == upper:
        return ordered[lower]

    fraction = position - lower
    return (
        ordered[lower] * (1.0 - fraction)
        + ordered[upper] * fraction
    )


def coordinates_look_geographic(x_values, y_values):
    return (
        x_values
        and y_values
        and all(-180.0 <= value <= 180.0 for value in x_values)
        and all(-90.0 <= value <= 90.0 for value in y_values)
    )


def project_coordinates(nodes):
    x_values = [node["x"] for node in nodes.values()]
    y_values = [node["y"] for node in nodes.values()]

    geographic = coordinates_look_geographic(x_values, y_values)

    if not geographic:
        return {
            node_id: (node["x"], node["y"])
            for node_id, node in nodes.items()
        }

    # Local equirectangular projection. This is sufficient for a city-scale
    # graph and prevents longitude from appearing horizontally stretched.
    mean_latitude = sum(y_values) / float(len(y_values))
    longitude_scale = math.cos(math.radians(mean_latitude))

    return {
        node_id: (
            node["x"] * longitude_scale,
            node["y"],
        )
        for node_id, node in nodes.items()
    }

def create_visualization(
    snapshot_path,
    output_path,
    timestamp,
    mode,
    ranks,
    stale_delay,
    node_size,
    edge_width,
    dpi,
):
    nodes, edges = load_snapshot(snapshot_path)
    coordinates = project_coordinates(nodes)

    # link.csv is expanded into two directed edges by city_load(). Plotting
    # both creates darker duplicate lines, so render each undirected road
    # segment once.
    undirected_segments = {}
    for edge in edges:
        src = edge["src"]
        dst = edge["dst"]
        key = (min(src, dst), max(src, dst))

        if key not in undirected_segments:
            undirected_segments[key] = (
                coordinates[src],
                coordinates[dst],
            )

    known_ids = []
    unknown_ids = []
    partial_ids = []

    for node_id in sorted(nodes):
        node = nodes[node_id]

        if node["age"] >= 0 and math.isfinite(node["age"]):
            known_ids.append(node_id)

            if node["partially_known"]:
                partial_ids.append(node_id)
        else:
            unknown_ids.append(node_id)

    known_ages = [nodes[node_id]["age"] for node_id in known_ids]

    figure, axes = plt.subplots(
        figsize=(16, 12),
        constrained_layout=True,
    )

    figure.patch.set_facecolor("#f3f1ec")
    axes.set_facecolor("#f3f1ec")

    road_collection = LineCollection(
        list(undirected_segments.values()),
        colors="#737373",
        linewidths=edge_width,
        alpha=0.32,
        zorder=1,
    )
    axes.add_collection(road_collection)

    if known_ids:
        color_max = percentile(known_ages, 98.0)
        color_max = max(1.0, color_max)

        normalization = Normalize(
            vmin=0.0,
            vmax=color_max,
            clip=True,
        )

        scatter = axes.scatter(
            [coordinates[node_id][0] for node_id in known_ids],
            [coordinates[node_id][1] for node_id in known_ids],
            c=known_ages,
            cmap="turbo",
            norm=normalization,
            s=node_size,
            linewidths=0.0,
            alpha=0.95,
            zorder=3,
        )

        colorbar = figure.colorbar(
            scatter,
            ax=axes,
            fraction=0.032,
            pad=0.015,
        )
        colorbar.set_label(
            "Replica age in ticks "
            "(maximum age of known outgoing edges)",
            fontsize=10,
        )

    if partial_ids:
        axes.scatter(
            [coordinates[node_id][0] for node_id in partial_ids],
            [coordinates[node_id][1] for node_id in partial_ids],
            facecolors="none",
            edgecolors="#111111",
            s=node_size * 2.0,
            linewidths=0.35,
            alpha=0.8,
            label="Partially observed",
            zorder=4,
        )

    if unknown_ids:
        axes.scatter(
            [coordinates[node_id][0] for node_id in unknown_ids],
            [coordinates[node_id][1] for node_id in unknown_ids],
            color="#3f3f3f",
            s=node_size * 1.25,
            linewidths=0.0,
            alpha=0.9,
            label="No observed state",
            zorder=5,
        )

    all_x = [position[0] for position in coordinates.values()]
    all_y = [position[1] for position in coordinates.values()]

    axes.set_xlim(min(all_x), max(all_x))
    axes.set_ylim(min(all_y), max(all_y))
    axes.margins(0.015)
    axes.set_aspect("equal", adjustable="box")
    axes.set_axis_off()

    if partial_ids or unknown_ids:
        axes.legend(
            loc="lower left",
            frameon=True,
            facecolor="white",
            framealpha=0.9,
        )

    known_count = len(known_ids)
    unknown_count = len(unknown_ids)
    partial_count = len(partial_ids)

    mean_age = (
        sum(known_ages) / float(known_count)
        if known_count
        else float("nan")
    )
    maximum_age = max(known_ages) if known_ages else float("nan")

    axes.set_title(
        "Congestion-replica staleness at tick {}\n"
        "mode={}, rank view=0, MPI ranks={}, stale delay={}".format(
            timestamp,
            mode,
            ranks,
            stale_delay,
        ),
        fontsize=15,
        pad=14,
    )

    summary = (
        "nodes: {:,}    roads: {:,}    directed edges: {:,}\n"
        "known: {:,}    partial: {:,}    unknown: {:,}\n"
        "mean known age: {:.2f} ticks    "
        "maximum known age: {:.0f} ticks"
    ).format(
        len(nodes),
        len(undirected_segments),
        len(edges),
        known_count,
        partial_count,
        unknown_count,
        mean_age,
        maximum_age,
    )

    axes.text(
        0.01,
        0.01,
        summary,
        transform=axes.transAxes,
        ha="left",
        va="bottom",
        fontsize=9,
        color="#202020",
        bbox={
            "boxstyle": "round,pad=0.5",
            "facecolor": "white",
            "edgecolor": "#999999",
            "alpha": 0.92,
        },
        zorder=10,
    )

    output_path.parent.mkdir(parents=True, exist_ok=True)

    figure.savefig(
        str(output_path),
        dpi=dpi,
        bbox_inches="tight",
        facecolor=figure.get_facecolor(),
    )

    plt.close(figure)

    print("Snapshot:      {}".format(snapshot_path))
    print("Visualization: {}".format(output_path))
    print("Nodes:         {}".format(len(nodes)))
    print("Road segments: {}".format(len(undirected_segments)))
    print("Known nodes:   {}".format(known_count))
    print("Partial nodes: {}".format(partial_count))
    print("Unknown nodes: {}".format(unknown_count))

def main() -> int:
    args = parse_arguments()

    try:
        data_dir = require_data_directory(args.data)
        node_path = data_dir / "node.csv"

        if args.snapshot_file is not None:
            snapshot_path = require_file(
                args.snapshot_file,
                "snapshot CSV",
            )
        else:
            snapshot_path = run_simulation(args)

        if args.output is None:
            output_path = (
                Path.cwd()
                / f"staleness-{args.mode}-t{args.timestamp}-rank0.png"
            )
        else:
            output_path = args.output.expanduser().resolve()

        create_visualization(
            snapshot_path=snapshot_path,
            output_path=output_path,
            timestamp=args.timestamp,
            mode=args.mode,
            ranks=args.ranks,
            stale_delay=args.stale_delay,
            node_size=args.node_size,
            edge_width=args.edge_width,
            dpi=args.dpi,
        )

    except (
        FileNotFoundError,
        PermissionError,
        ValueError,
        RuntimeError,
        OSError,
    ) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
