#!/usr/bin/env python3
"""
Run graph_traffic with 32 MPI ranks and visualize rank 0's congestion-replica
staleness snapshot.

Expected directory layout:

    graph_traffic/
    ├── traffic
    ├── data/
    │   ├── node.csv
    │   └── link.csv
    └── scripts/
        └── vis/
            └── visualize_staleness.py

The traffic executable must support:

    --snapshot-dump TIMESTAMP

and produce:

    staleness-<mode>-t<TIMESTAMP>-rank0.csv

The snapshot CSV is expected to contain the fields generated by the C code:

    record_type,node_id,edge_id,src,dst,stamp,age,value,
    known_edges,total_edges

Only rank 0's replica is visualized. Nodes are colored by the maximum age of
their known outgoing-edge congestion entries. Unknown nodes are gray.
"""

